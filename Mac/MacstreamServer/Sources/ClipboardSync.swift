import AppKit

/// Clipboard sync with the PC: text and pictures (PNG), over the encrypted connection
/// (CLIPBOARD packet, see PROTOCOL.md).
///
/// Privacy rules:
/// - The PC's toggle decides. The Mac only watches its clipboard after the PC sends "sync on",
///   stops on "sync off" or disconnect, and accepts copies from the PC only while on.
/// - Only copies made while sync is on are sent. Whatever was on the clipboard before is not
///   sent, and there is no history: each copy replaces the last one.
/// - Copies that apps mark as concealed or transient (password managers) are never sent.
/// - Contents are never logged, only their size.
/// - A copy with both text and a picture sends the text. Copied files are not sent.
/// - MACSTREAM_CLIPBOARD=0 turns it off on the Mac whatever the PC asks.
///
/// All state lives on the main queue (NSPasteboard is used there).
final class ClipboardSync {
    static let maxTextBytes = 512 * 1024
    /// Largest picture either way, as PNG (a full Retina screenshot is 3-6 MB). The server's
    /// receive limits (FrameServer, ServerHandshake) leave room for it.
    static let maxImageBytes = 12 * 1024 * 1024

    private enum Kind: UInt8 {
        case syncOn = 0x01
        case syncOff = 0x02
        case text = 0x03
        case image = 0x04
    }

    /// Types that clipboard tools use to say "don't record or share this" (nspasteboard.org).
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private static let pngSignature: [UInt8] = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]

    private let allowed: Bool
    private let send: (Data) -> Void
    private var enabled = false
    private var lastChangeCount = 0
    private var timer: DispatchSourceTimer?

    /// Called on the main queue when sync turns on or off.
    var onStateChange: ((Bool) -> Void)?

    init(allowed: Bool, send: @escaping (Data) -> Void) {
        self.allowed = allowed
        self.send = send
    }

    /// One CLIPBOARD payload from the PC. Safe to call from any thread.
    func handle(payload: Data) {
        let bytes = [UInt8](payload)
        DispatchQueue.main.async { [weak self] in
            self?.process(bytes)
        }
    }

    /// The PC disconnected: stop watching. Safe to call from any thread.
    func clientDisconnected() {
        DispatchQueue.main.async { [weak self] in
            self?.setEnabled(false, reason: "PC disconnected")
        }
    }

    private func process(_ bytes: [UInt8]) {
        guard let first = bytes.first, let kind = Kind(rawValue: first) else { return }
        switch kind {
        case .syncOn:
            guard allowed else {
                print("\(ServerText.mainTag) clipboard sync requested by the PC but MACSTREAM_CLIPBOARD=0")
                return
            }
            setEnabled(true, reason: "turned on in the Windows app")
        case .syncOff:
            setEnabled(false, reason: "turned off in the Windows app")
        case .text:
            guard enabled, bytes.count > 1, bytes.count - 1 <= Self.maxTextBytes,
                  let text = String(bytes: bytes[1...], encoding: .utf8) else { return }
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            lastChangeCount = pasteboard.changeCount   // don't send it straight back
            print("\(ServerText.mainTag) clipboard: received \(bytes.count - 1) bytes of text from the PC")
        case .image:
            guard enabled, bytes.count > Self.pngSignature.count + 1, bytes.count - 1 <= Self.maxImageBytes,
                  Array(bytes[1...Self.pngSignature.count]) == Self.pngSignature else { return }
            let png = Data(bytes[1...])
            // Decoding checks it really is a picture before it goes on the clipboard.
            guard let rep = NSBitmapImageRep(data: png) else {
                print("\(ServerText.mainTag) clipboard: ignored an unreadable picture from the PC")
                return
            }
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            pasteboard.setData(png, forType: .png)
            // TIFF too, for older apps that only read that.
            if let tiff = rep.tiffRepresentation(using: .lzw, factor: 0) {
                pasteboard.setData(tiff, forType: .tiff)
            }
            lastChangeCount = pasteboard.changeCount
            print("\(ServerText.mainTag) clipboard: received a \(rep.pixelsWide)x\(rep.pixelsHigh) picture (\(png.count) bytes) from the PC")
        }
    }

    private func setEnabled(_ value: Bool, reason: String) {
        guard value != enabled else { return }
        enabled = value
        if value {
            // Start from the current state: what is already on the clipboard is not sent.
            lastChangeCount = NSPasteboard.general.changeCount
            let timer = DispatchSource.makeTimerSource(queue: .main)
            timer.schedule(deadline: .now() + 0.5, repeating: 0.5)
            timer.setEventHandler { [weak self] in self?.poll() }
            timer.resume()
            self.timer = timer
        } else {
            timer?.cancel()
            timer = nil
        }
        print("\(ServerText.mainTag) clipboard sync \(value ? "on" : "off") (\(reason))")
        onStateChange?(value)
    }

    /// macOS has no clipboard-changed notification; checking a counter twice a second is cheap.
    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard enabled, count != lastChangeCount else { return }
        lastChangeCount = count

        let types = Set((pasteboard.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: Self.privateTypes) else {
            print("\(ServerText.mainTag) clipboard: skipped a copy marked private (e.g. a password manager)")
            return
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            sendText(text)
            return
        }
        // Copied files carry their icons as pictures; the icon isn't what was copied.
        guard !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }
        if let png = pictureAsPNG(pasteboard) {
            sendPicture(png)
        }
    }

    private func sendText(_ text: String) {
        let utf8 = Data(text.utf8)
        guard utf8.count <= Self.maxTextBytes else {
            print("\(ServerText.mainTag) clipboard: skipped \(utf8.count) bytes of text (limit \(Self.maxTextBytes))")
            return
        }
        var payload = Data([Kind.text.rawValue])
        payload.append(utf8)
        send(payload)
        print("\(ServerText.mainTag) clipboard: sent \(utf8.count) bytes of text to the PC")
    }

    /// The picture on the clipboard as PNG: the PNG itself if an app put one there (screenshots
    /// do), otherwise the TIFF converted.
    private func pictureAsPNG(_ pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png), png.starts(with: Self.pngSignature) {
            return png
        }
        guard let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else {
            return nil
        }
        return rep.representation(using: .png, properties: [:])
    }

    private func sendPicture(_ png: Data) {
        guard png.count <= Self.maxImageBytes else {
            print("\(ServerText.mainTag) clipboard: skipped a \(png.count / 1024 / 1024) MB picture (limit \(Self.maxImageBytes / 1024 / 1024) MB)")
            return
        }
        var payload = Data([Kind.image.rawValue])
        payload.append(png)
        send(payload)
        print("\(ServerText.mainTag) clipboard: sent a picture (\(png.count) bytes) to the PC")
    }
}
